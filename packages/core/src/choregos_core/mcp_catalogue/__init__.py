"""The catalogue of well-known MCP servers shipped with the platform (ADR 0065).

`catalogue.yaml` is generated by `tools/catalogues/build_mcp_catalogue.py` from a reviewed seed and
recorded answers of the official MCP Registry and GitHub; nothing here reads the network. An entry
is an offer: installing it creates an ordinary organisation `mcp` connector, with its tools born
closed, through the existing governance.

What an entry *can do* in this release (`install_kind`) is computed from the entry and the code, never
stored in the file: when a connector learns to carry an OAuth credential, entries flip with no
change to the catalogue.
"""

from __future__ import annotations

import functools
import json
from datetime import date
from pathlib import Path
from typing import Literal

import yaml
from jsonschema import Draft202012Validator
from pydantic import BaseModel, ConfigDict, Field

from choregos_core.catalogues import CatalogueError, CatalogueMeta, meta_of, read_catalogue

HERE = Path(__file__).parent
CATALOGUE_PATH = HERE / "catalogue.yaml"
SCHEMA_PATH = HERE / "schema.json"

InstallKind = Literal["installable", "needs_oauth", "needs_hosting"]

#: How the generator sorts: what can be installed now comes first.
INSTALL_ORDER: dict[str, int] = {"installable": 0, "needs_oauth": 1, "needs_hosting": 2}


class McpRemote(BaseModel):
    model_config = ConfigDict(extra="forbid")

    url: str
    protocol: Literal["streamable-http", "sse"]


class McpHosting(BaseModel):
    model_config = ConfigDict(extra="forbid")

    package: str
    version: str | None = None


class McpEntry(BaseModel):
    """One catalogue line. `auth` is `none`, `bearer`, `oauth` or `header:<Name>`."""

    model_config = ConfigDict(extra="forbid")

    id: str
    title: str
    description: str
    publisher: str
    official: bool
    reference: bool
    registry_name: str | None = None
    registry_version: str | None = None
    repo: str | None = None
    licence: str | None = None
    terms_url: str | None = None
    transport: Literal["remote", "stdio"]
    remote: McpRemote | None = None
    auth: str
    egress_hosts: list[str] = Field(default_factory=list)
    categories: list[str]
    stars: int | None = None
    stars_as_of: date | None = None
    hosting: McpHosting | None = None
    #: Where the entry comes from: the shipped file, or the operator's own (`site`). Not in the file.
    origin: Literal["catalogue", "site"] = Field(default="catalogue", exclude=True)

    @property
    def install(self) -> InstallKind:
        return install_kind(self)

    @property
    def auth_header(self) -> str | None:
        """The header name an `auth: header:<Name>` entry sends the secret in."""
        return self.auth.partition(":")[2] if self.auth.startswith("header:") else None


class McpCatalogue(BaseModel):
    meta: CatalogueMeta
    entries: list[McpEntry]

    def by_id(self, entry_id: str) -> McpEntry | None:
        return next((e for e in self.entries if e.id == entry_id), None)


def install_kind(entry: McpEntry) -> InstallKind:
    """What this release can do with an entry.

    A stdio server is `needs_hosting`: running a third party's process is the operator's decision.
    A remote that authenticates with OAuth is `needs_oauth`: an organisation connector carries a
    static secret, not a per-user authorisation. Everything else is a connector pre-filled.
    """
    if entry.transport == "stdio" or entry.remote is None or entry.remote.protocol != "streamable-http":
        return "needs_hosting"
    if entry.auth == "oauth":
        return "needs_oauth"
    return "installable"


@functools.lru_cache(maxsize=1)
def load() -> McpCatalogue:
    """The shipped catalogue, validated once."""
    raw = read_catalogue(CATALOGUE_PATH, SCHEMA_PATH)
    return McpCatalogue(meta=meta_of(raw), entries=[McpEntry.model_validate(e) for e in raw["entries"]])


def entry(entry_id: str) -> McpEntry | None:
    """The entry with this id, or `None`."""
    return load().by_id(entry_id)


def _read_site_entries(path: Path) -> list[McpEntry]:
    """The operator's own entries (`{entries: [...]}`), each validated like a shipped one."""
    raw = yaml.safe_load(path.read_text(encoding="utf-8"))
    if not isinstance(raw, dict) or not isinstance(raw.get("entries"), list):
        raise CatalogueError(f"{path.name}: expected a mapping with an `entries` list")
    schema = json.loads(SCHEMA_PATH.read_text(encoding="utf-8"))
    validator = Draft202012Validator({"$ref": "#/$defs/entry", "$defs": schema["$defs"]})
    entries: list[McpEntry] = []
    for index, item in enumerate(raw["entries"]):
        problems = sorted(validator.iter_errors(item), key=lambda e: list(e.absolute_path))
        if problems:
            detail = "; ".join(
                f"{'/'.join(str(p) for p in e.absolute_path) or '<entry>'}: {e.message}" for e in problems[:5]
            )
            raise CatalogueError(f"{path.name}: entry {index} ({item.get('id', '?')}): {detail}")
        entries.append(McpEntry.model_validate(item).model_copy(update={"origin": "site"}))
    return entries


@functools.lru_cache(maxsize=4)
def load_with_site(site_path: str | None) -> McpCatalogue:
    """The shipped catalogue followed by the operator's own file, when there is one.

    An id the shipped catalogue already holds is refused rather than shadowed: an operator entry
    that silently replaced `github` would be a way to point an installed-by-name server elsewhere.
    """
    base = load()
    if not site_path:
        return base
    extra = _read_site_entries(Path(site_path))
    taken = {e.id for e in base.entries}
    clash = sorted(e.id for e in extra if e.id in taken)
    if clash:
        raise CatalogueError(
            f"{Path(site_path).name}: ids already in the shipped catalogue: {', '.join(clash)}"
        )
    ids = [e.id for e in extra]
    if len(ids) != len(set(ids)):
        raise CatalogueError(f"{Path(site_path).name}: duplicate ids")
    sources = {**base.meta.sources, "site_catalogue": Path(site_path).name}
    return McpCatalogue(
        meta=base.meta.model_copy(update={"sources": sources}), entries=[*base.entries, *extra]
    )
