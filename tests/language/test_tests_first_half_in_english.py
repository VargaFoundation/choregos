"""S45-30: the first half of the tests tree is English, and the former French directory is gone.

`tools/check_english.py` counts French prose lines, French declared names and French path
components in every tracked file. This test runs its tree scan over the directories this story
renamed and translated (`tests/language`, `tests/docs` except `test_links.py`, `tests/ci`,
`tests/dev`, `tests/licences`, `tests/integrations`, `tests/charts`) and refuses any finding, so a
French comment or a French local name cannot come back without the suite turning red.

The directory used to have a French name (see `OLD_DIRECTORY`). Nothing but the plan and the
reference pages (renamed by their own story) may still name it: a code, CI or ADR reference to the
old path would be a dead link.
"""

from __future__ import annotations

import importlib.util
import pathlib
import subprocess
import sys
from types import ModuleType

ROOT = pathlib.Path(__file__).resolve().parents[2]
PREFIXES = (
    "tests/language/",
    "tests/docs/",
    "tests/ci/",
    "tests/dev/",
    "tests/licences/",
    "tests/integrations/",
    "tests/charts/",
)
#: Owned by another story (S45-38).
EXCLUDED = ("tests/docs/test_links.py",)
#: The old directory name, split so that this file does not name it.
OLD_DIRECTORY = "tests/" + "langue"  # lang: fr-ok
#: Where the old name may still appear: the plan and the reference pages (S45-44), the baselines
#: (regenerated by the integrator) and ADR 0098, which records the French paths it measured.
ALLOWED = (
    ":(exclude,glob)docs/*.md",
    ":(exclude)docs/plan",
    ":(exclude)tools/english_baseline",
    ":(exclude)docs/adr/0098-english-everywhere-finished.md",
)


def _load_checker() -> ModuleType:
    spec = importlib.util.spec_from_file_location(
        "check_english_for_tests_first_half", ROOT / "tools" / "check_english.py"
    )
    assert spec is not None and spec.loader is not None
    module = importlib.util.module_from_spec(spec)
    sys.modules[spec.name] = module
    spec.loader.exec_module(module)
    return module


def test_owned_test_dirs_have_no_french() -> None:
    checker = _load_checker()
    findings = [f for f in checker.scan_tree(PREFIXES) if f.path not in EXCLUDED]
    assert findings == [], "\n".join(
        f"{f.path}:{f.line}: {f.reason}: {f.text.strip()[:100]}" for f in findings
    )


def test_no_code_or_adr_names_tests_langue() -> None:
    result = subprocess.run(
        ["git", "grep", "-n", "-F", OLD_DIRECTORY, "--", ".", *ALLOWED],
        cwd=ROOT,
        capture_output=True,
        text=True,
        check=False,
    )
    assert result.returncode == 1, f"{OLD_DIRECTORY} is still named:\n{result.stdout}"
    assert (ROOT / "tests" / "language").is_dir()
    assert not (ROOT / OLD_DIRECTORY).exists()
