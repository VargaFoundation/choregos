import difflib
import fnmatch
import gzip
import hashlib
import io
import json
import shutil
import sys
import tarfile
from dataclasses import dataclass
from datetime import date
from pathlib import Path
from typing import Any

import httpx
import yaml
from choregos_api.services.skill_gate import OPEN_LICENCES, assess
from choregos_api.services.skill_sources import (
    LICENCE_FILES,
    FoundSkill,
    Snapshot,
    detect_licence,
    read_tarball,
)
from choregos_api.services.skills import empreinte
from choregos_contracts.skill_files import skill_file_bytes

from tools.catalogues import _github, _recording

ROOT = Path(__file__).resolve().parents[2]
SEED_DIR = ROOT / "tools" / "catalogues" / "skills"
FIXTURES = ROOT / "tests" / "fixtures" / "catalogues" / "skills"
CORE = ROOT / "packages" / "core" / "src" / "choregos_core" / "skill_catalogue"
OUTPUT = CORE / "catalogue.yaml"
BUNDLED = CORE / "bundled"
NOTICES = ROOT / "THIRD_PARTY_NOTICES.md"
WEB_MOCK = ROOT / "apps" / "web" / "src" / "mocks" / "skill-catalogue.json"

#: Licences a skill may be redistributed under in the image. The other open ones (MPL, GPL, CC-BY-SA…)
#: are copyleft: listed, fetched at install, never bundled into an Apache-2.0 image.
PERMISSIVE = frozenset(
    {"0BSD", "Apache-2.0", "BSD-2-Clause", "BSD-3-Clause", "CC-BY-4.0", "CC0-1.0", "ISC", "MIT", "Unlicense"}
)
CATEGORIES = frozenset(
    {
        "engineering", "review", "testing", "security", "documentation", "product", "design", "data",
        "finance", "legal", "hr", "sales", "marketing", "operations", "support", "cloud", "research",
    }
)  # fmt: skip
DESCRIPTION_MAX = 300
HEADER = (
    "# Generated by tools/catalogues/build_skill_catalogue.py from tools/catalogues/skills/ and the\n"
    "# recordings in tests/fixtures/catalogues/skills/. Do not edit by hand: change the seed and run\n"
    "# `make catalogues`. ADR 0065. Nothing here is installed by default: an entry is an offer an\n"
    "# administrator installs, and the supply-chain gate runs again at install.\n"
)
ENTRY_KEYS = (
    "id", "title", "description", "publisher", "repo", "sha", "path", "licence", "licence_class",
    "files", "bytes", "digest", "risk", "findings_count", "categories", "signals", "delivery",
)  # fmt: skip


class GeneratorError(RuntimeError):
    """The inputs contradict each other; fix the seed."""


@dataclass(frozen=True)
class Dropped:
    entry_id: str
    reason: str


@dataclass(frozen=True)
class Note:
    entry_id: str
    text: str


# ------------------------------------------------------------------------------ recording


def _load_yaml(name: str) -> Any:
    return yaml.safe_load((SEED_DIR / name).read_text(encoding="utf-8"))


def tarball_name(repo: str, sha: str) -> str:
    owner, _, name = repo.partition("/")
    return f"{owner}__{name}__{sha[:12]}.tar.gz"


def reduce_tarball(content: bytes, keep: list[str]) -> bytes:
    """A tarball holding only the folders of `keep` and the licence files at the root, byte-stable.

    The commit's top folder is kept, the members are sorted, and owner, time and gzip header are zeroed,
    so recording the same commit twice gives the same bytes."""
    out = io.BytesIO()
    with tarfile.open(fileobj=io.BytesIO(content), mode="r:*") as source:
        members: list[tuple[str, tarfile.TarInfo]] = []
        for info in source:
            if not info.isfile() or "/" not in info.name:
                continue
            relative = info.name.split("/", 1)[1]
            if relative in LICENCE_FILES or any(relative.startswith(prefix + "/") for prefix in keep):
                members.append((info.name, info))
        members.sort(key=lambda m: m[0])
        with (
            gzip.GzipFile(fileobj=out, mode="wb", mtime=0) as gz,
            tarfile.open(fileobj=gz, mode="w", format=tarfile.PAX_FORMAT) as target,
        ):
            for name, info in members:
                data = source.extractfile(info)
                assert data is not None
                clean = tarfile.TarInfo(name)
                clean.size, clean.mode, clean.mtime = info.size, info.mode, 0
                target.addfile(clean, io.BytesIO(data.read()))
    return out.getvalue()


def _find(snapshot: Snapshot, line: dict[str, Any]) -> tuple[FoundSkill | None, str | None]:
    """The folder a seed line names, or why there is none."""
    name = line["name"]
    candidates = [s for s in snapshot.skills if s.name == name]
    if "path" in line:
        candidates = [s for s in candidates if s.path == line["path"]]
    if len(candidates) > 1:
        paths = ", ".join(s.path for s in candidates)
        raise GeneratorError(f"{name}: {len(candidates)} folders carry that name ({paths}); give a `path`")
    return (candidates[0], None) if candidates else (None, f"no skill named {name} in the repository")


def record_sources(directory: Path, seed: list[dict[str, Any]], token: str) -> None:
    """The one place that touches the network: pin each repository's `ref`, record GitHub's facts and
    keep a reduced tarball of the commit."""
    directory.mkdir(parents=True, exist_ok=True)
    for stale in [*directory.glob("*.json"), *directory.glob("*.tar.gz")]:
        stale.unlink()
    headers = {"Authorization": f"Bearer {token}", "Accept": "application/vnd.github+json"}
    repos: dict[str, Any] = {}
    with httpx.Client(headers=headers, timeout=120, follow_redirects=True) as live:
        for block in seed:
            repo, ref = block["repo"], block["ref"]
            sha = live.get(
                f"https://api.github.com/repos/{repo}/commits/{ref}",
                headers={"Accept": "application/vnd.github.sha"},
            )
            sha.raise_for_status()
            commit = sha.text.strip()
            tar = live.get(f"https://codeload.github.com/{repo}/tar.gz/{commit}")
            tar.raise_for_status()
            snapshot = read_tarball(tar.content, "")
            resolved: dict[str, Any] = {}
            keep: list[str] = []
            for line in block["skills"]:
                found, why = _find(snapshot, line)
                problem = why or (found.problem if found else None)
                resolved[line["name"]] = {"path": found.path if found else None, "problem": problem}
                if found and not found.problem:
                    keep.append(found.path)
            (directory / tarball_name(repo, commit)).write_bytes(reduce_tarball(tar.content, keep))
            repos[repo] = {"ref": ref, "sha": commit, "skills": resolved}
    with _recording.make_client(directory, record=True, headers=headers) as client:
        _github.fetch_repo_facts(client, list(repos))
    meta = {"recorded_at": date.today().isoformat(), "repos": repos}
    (directory / "meta.json").write_text(json.dumps(meta, indent=1, sort_keys=True) + "\n", encoding="utf-8")


def read_meta(directory: Path) -> dict[str, Any]:
    return json.loads((directory / "meta.json").read_text(encoding="utf-8"))  # type: ignore[no-any-return]


# ------------------------------------------------------------------------------ resolution


def description_of(text: str | None) -> str:
    """The frontmatter description on one line, cut at 300 characters."""
    one = " ".join((text or "").split())
    return one if len(one) <= DESCRIPTION_MAX else one[: DESCRIPTION_MAX - 1].rstrip() + "…"


def title_of(entry_id: str) -> str:
    words = entry_id.replace("-", " ")
    return words[:1].upper() + words[1:]


def excluded(name: str, path: str, exclusions: dict[str, Any]) -> str | None:
    for rule in exclusions.get("names", []):
        if fnmatch.fnmatchcase(name, rule["pattern"]):
            return str(rule["reason"])
    for rule in exclusions.get("paths", []):
        if fnmatch.fnmatchcase(path, rule["pattern"]):
            return str(rule["reason"])
    return None


def licence_file_of(found: FoundSkill, snapshot: Snapshot) -> tuple[str, str, str] | None:
    """(scope, file name, text) of the licence file `detect_licence` reads: the skill's, then the repo's."""
    for scope, files in (("skill", found.files), ("repository", snapshot.licences)):
        for name in LICENCE_FILES:
            if name in files:
                return scope, name, files[name]
    return None


def check_publisher(owner: str, facts: _github.RepoFacts | None, publishers: dict[str, Any]) -> str | None:
    """The reason the owner may not publish here, or `None`."""
    rule = publishers["publishers"].get(owner)
    if rule is None:
        return f"{owner} is not on the publisher list"
    if facts is None:
        return "the repository is not found on GitHub"
    if facts.archived:
        return "the repository is archived"
    if not rule["vendor"] and facts.stars < publishers["min_stars"]:
        return f"{facts.stars} stars: a maintainer needs {publishers['min_stars']}"
    return None


def resolve(
    repo: str,
    line: dict[str, Any],
    recorded: dict[str, Any],
    snapshot: Snapshot,
    facts: _github.RepoFacts | None,
    publishers: dict[str, Any],
    exclusions: dict[str, Any],
    recorded_at: str,
) -> tuple[dict[str, Any], dict[str, str] | None] | Dropped:
    """One seed line → one entry (and what to vendor when it is bundled), or the reason it is dropped."""
    entry_id = line["name"]
    unknown = sorted(set(line.get("categories", [])) - CATEGORIES)
    if unknown or not line.get("categories"):
        raise GeneratorError(
            f"{entry_id}: categories {line.get('categories')} are not in {sorted(CATEGORIES)}"
        )
    owner = repo.split("/", 1)[0]
    if why := check_publisher(owner, facts, publishers):
        return Dropped(entry_id, f"publisher: {why}")
    resolution = recorded["skills"][entry_id]
    if resolution["path"] is None or resolution["problem"]:
        return Dropped(entry_id, f"gate: {resolution['problem']}")
    if why := excluded(entry_id, f"{repo}/{resolution['path']}", exclusions):
        return Dropped(entry_id, f"excluded: {why}")
    found = next((s for s in snapshot.skills if s.path == resolution["path"]), None)
    if found is None or found.problem or found.name != entry_id:
        raise GeneratorError(
            f"{entry_id}: the recorded tarball does not hold it at {resolution['path']}: re-record"
        )
    licence = detect_licence(found.files, snapshot.licences)
    if licence not in OPEN_LICENCES:
        return Dropped(entry_id, f"licence: {licence or 'none found'} is not an open-source licence")
    assessment = assess(found.files, executables=found.executables, repo_licences=snapshot.licences)
    permissive = licence in PERMISSIVE
    delivery = "git"
    if line.get("delivery") == "bundled" and permissive and assessment.risk != "high":
        delivery = "bundled"
    notes = None
    if delivery == "bundled":
        owned = licence_file_of(found, snapshot)
        if owned is None:
            raise GeneratorError(f"{entry_id}: {licence} was detected but no licence file backs it")
        notes = {"scope": owned[0], "name": owned[1], "text": owned[2]}
    entry = {
        "id": entry_id,
        "title": line.get("title") or title_of(entry_id),
        "description": description_of(found.description),
        "publisher": publishers["publishers"][owner]["name"],
        "repo": f"https://github.com/{repo}",
        "sha": recorded["sha"],
        "path": found.path,
        "licence": licence,
        "licence_class": "permissive" if permissive else "copyleft",
        "files": len(found.files),
        "bytes": sum(len(skill_file_bytes(p, t)) for p, t in found.files.items()),
        "digest": empreinte(found.files),
        "risk": assessment.risk,
        "findings_count": len(assessment.findings),
        "categories": sorted(line["categories"]),
        "signals": {"stars": facts.stars if facts else None, "stars_as_of": recorded_at},
        "delivery": delivery,
    }
    if line.get("delivery") == "bundled" and delivery == "git":
        why = "a copyleft licence" if not permissive else f"{assessment.risk} risk"
        return entry, {"downgraded": f"asked bundled, delivered by git: {why}"}
    return entry, notes


def build(
    seed: list[dict[str, Any]],
    meta: dict[str, Any],
    snapshots: dict[str, Snapshot],
    facts: dict[str, _github.RepoFacts | None],
    publishers: dict[str, Any],
    exclusions: dict[str, Any],
    catalogue_version: str,
) -> tuple[dict[str, Any], dict[str, dict[str, Any]], list[Dropped], list[Note]]:
    """The catalogue (a dict), the bundled trees to write, the dropped lines and the downgrades."""
    recorded_at = meta["recorded_at"]
    entries: list[dict[str, Any]] = []
    bundles: dict[str, dict[str, Any]] = {}
    drops: list[Dropped] = []
    notes: list[Note] = []
    seen: dict[str, str] = {}
    for block in seed:
        repo = block["repo"]
        owner_repo = _github.parse_repo(repo)
        assert owner_repo is not None
        repo_facts = facts.get(f"{owner_repo[0]}/{owner_repo[1]}")
        for line in block["skills"]:
            name = line["name"]
            if name in seen:
                raise GeneratorError(
                    f"{name} is in the seed twice ({seen[name]} and {repo}): one entry per skill name"
                )
            seen[name] = repo
            result = resolve(
                repo,
                line,
                meta["repos"][repo],
                snapshots[repo],
                repo_facts,
                publishers,
                exclusions,
                recorded_at,
            )
            if isinstance(result, Dropped):
                drops.append(result)
                continue
            entry, extra = result
            entries.append(entry)
            if extra and "downgraded" in extra:
                notes.append(Note(name, extra["downgraded"]))
            elif extra is not None:
                found = next(s for s in snapshots[repo].skills if s.path == entry["path"])
                bundles[name] = {"entry": entry, "files": found.files, "licence": extra}
    entries.sort(
        key=lambda e: (0 if e["delivery"] == "bundled" else 1, -(e["signals"]["stars"] or 0), e["id"])
    )
    document = {
        "schema_version": 1,
        "catalogue_version": catalogue_version,
        "generated_at": f"{recorded_at}T00:00:00Z",
        "sources": {
            "github": f"https://api.github.com (commits pinned {recorded_at})",
            "github_stars_as_of": recorded_at,
        },
        "entries": entries,
    }
    return document, bundles, drops, notes


# ------------------------------------------------------------------------------ rendering


def render(document: dict[str, Any]) -> str:
    ordered = dict(document)
    ordered["entries"] = [{k: e[k] for k in ENTRY_KEYS} for e in document["entries"]]
    return HEADER + yaml.safe_dump(
        ordered, sort_keys=False, allow_unicode=True, width=110, default_flow_style=False
    )


def sha256(text: str) -> str:
    return hashlib.sha256(text.encode("utf-8")).hexdigest()


def bundled_tree(bundles: dict[str, dict[str, Any]]) -> dict[Path, bytes]:
    """Every file of the bundled starter set, by path relative to `bundled/`."""
    tree: dict[Path, bytes] = {}
    for entry_id, bundle in sorted(bundles.items()):
        entry, files, licence = bundle["entry"], bundle["files"], bundle["licence"]
        # a font or an image is stored as base64 (ADR 0050): the tree holds its real bytes
        stored = {relative: skill_file_bytes(relative, text) for relative, text in sorted(files.items())}
        for relative, data in stored.items():
            tree[Path(entry_id) / "files" / relative] = data
        licence_file: dict[str, str] = {
            "scope": licence["scope"],
            "name": licence["name"],
            "sha256": sha256(licence["text"]),
        }
        if licence["scope"] == "repository":
            tree[Path(entry_id) / "LICENSE"] = licence["text"].encode("utf-8")
            licence_file["stored_as"] = "LICENSE"
        provenance = {
            "id": entry_id,
            "repo": entry["repo"],
            "sha": entry["sha"],
            "path": entry["path"],
            "licence": entry["licence"],
            "licence_file": licence_file,
            "files": {relative: hashlib.sha256(data).hexdigest() for relative, data in stored.items()},
        }
        tree[Path(entry_id) / "PROVENANCE.json"] = (
            json.dumps(provenance, indent=1, sort_keys=True) + "\n"
        ).encode()
    return tree


def notices(document: dict[str, Any]) -> str:
    """THIRD_PARTY_NOTICES.md: what the image redistributes, from whom, under which licence."""
    by_repo: dict[str, list[dict[str, Any]]] = {}
    for entry in document["entries"]:
        if entry["delivery"] == "bundled":
            by_repo.setdefault(entry["repo"], []).append(entry)
    lines = [
        "# Third-party notices",
        "",
        "<!-- Generated by tools/catalogues/build_skill_catalogue.py. Do not edit by hand. -->",
        "",
        "Choregos itself is Apache-2.0 (see `LICENSE`). Its image also carries the starter set of the skills",
        "catalogue ([ADR 0065](docs/adr/0065-catalogues-of-mcp-servers-and-skills.md)): skills written by",
        "others, redistributed verbatim under their own permissive licence. Each skill's licence text and",
        "provenance sit next to it under `packages/core/src/choregos_core/skill_catalogue/bundled/<skill>/`.",
        "",
    ]
    for repo, entries in sorted(by_repo.items()):
        licences = sorted({e["licence"] for e in entries})
        lines += [
            f"## {repo.removeprefix('https://github.com/')}",
            "",
            f"- Source: <{repo}> at commit `{entries[0]['sha']}`",
            f"- Licence: {', '.join(licences)}",
            f"- Skills: {', '.join(f'`{e["id"]}`' for e in sorted(entries, key=lambda e: e['id']))}",
            "",
        ]
    return "\n".join(lines)


def render_web_mock(document: dict[str, Any]) -> str:
    """The catalogue as `GET /orgs/{org}/skill-catalogue` shows it before anything is installed."""
    entries = [
        {k: e[k] for k in ENTRY_KEYS}
        | {"state": "available", "installed_version": None, "blocked_reason": None}
        for e in document["entries"]
    ]
    meta = {
        "catalogue_version": document["catalogue_version"],
        "generated_at": document["generated_at"],
        "sources": document["sources"],
    }
    return json.dumps({"meta": meta, "entries": entries}, indent=1, ensure_ascii=False) + "\n"


def write_tree(root: Path, tree: dict[Path, bytes]) -> None:
    if root.exists():
        shutil.rmtree(root)
    for relative, data in tree.items():
        path = root / relative
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(data)


def read_tree(root: Path) -> dict[Path, bytes]:
    if not root.exists():
        return {}
    return {p.relative_to(root): p.read_bytes() for p in sorted(root.rglob("*")) if p.is_file()}


# ------------------------------------------------------------------------------ main


def load_inputs(
    directory: Path, seed: list[dict[str, Any]]
) -> tuple[dict[str, Any], dict[str, Snapshot], dict[str, _github.RepoFacts | None]]:
    meta = read_meta(directory)
    snapshots = {
        block["repo"]: read_tarball(
            (directory / tarball_name(block["repo"], meta["repos"][block["repo"]]["sha"])).read_bytes(), ""
        )
        for block in seed
    }
    with _recording.make_client(directory, record=False) as client:
        facts = _github.fetch_repo_facts(client, [b["repo"] for b in seed])
    return meta, snapshots, facts


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument(
        "--record", action="store_true", help="re-pin the commits and re-record from the network"
    )
    mode.add_argument("--check", action="store_true", help="replay and fail if a committed file differs")
    args = parser.parse_args(argv)

    seed = _load_yaml("seed.yaml")
    publishers = _load_yaml("publishers.yaml")
    exclusions = _load_yaml("exclusions.yaml")
    overrides = _load_yaml("overrides.yaml")
    if args.record:
        import os

        token = os.environ.get("GITHUB_TOKEN")
        if not token:
            print("--record needs GITHUB_TOKEN (for example `gh auth token`)", file=sys.stderr)
            return 2
        record_sources(FIXTURES, seed, token)

    meta, snapshots, facts = load_inputs(FIXTURES, seed)
    document, bundles, drops, notes = build(
        seed, meta, snapshots, facts, publishers, exclusions, overrides["catalogue_version"]
    )
    for drop in drops:
        print(f"dropped {drop.entry_id}: {drop.reason}", file=sys.stderr)
    for note in notes:
        print(f"note {note.entry_id}: {note.text}", file=sys.stderr)
    bundled = sum(1 for e in document["entries"] if e["delivery"] == "bundled")
    print(f"{len(document['entries'])} entries ({bundled} bundled), {len(drops)} dropped", file=sys.stderr)

    tree = bundled_tree(bundles)
    files = {
        OUTPUT: render(document).encode(),
        NOTICES: notices(document).encode(),
        WEB_MOCK: render_web_mock(document).encode(),
    }
    if args.check:
        stale = False
        for path, wanted in files.items():
            current = path.read_bytes() if path.exists() else b""
            if current != wanted:
                stale = True
                sys.stderr.writelines(
                    difflib.unified_diff(
                        current.decode().splitlines(keepends=True),
                        wanted.decode().splitlines(keepends=True),
                        "committed",
                        "generated",
                    )
                )
                print(f"{path.name} is out of date: run `make catalogues`", file=sys.stderr)
        if read_tree(BUNDLED) != tree:
            stale = True
            current_tree = read_tree(BUNDLED)
            names = sorted(
                str(p) for p in set(current_tree) | set(tree) if current_tree.get(p) != tree.get(p)
            )
            print(f"the bundled starter set is out of date: {names[:10]}", file=sys.stderr)
        return 1 if stale else 0
    for path, wanted in files.items():
        path.write_bytes(wanted)
    write_tree(BUNDLED, tree)
    return 0


if __name__ == "__main__":
    sys.exit(main())
