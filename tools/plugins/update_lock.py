#!/usr/bin/env python3
"""The plugins the core ships offline: `plugins/offline/` and its `plugins.lock` (ADR 0093 §6, S43-09).

    uv run python -m tools.plugins.update_lock            # a maintainer, WITH network: refresh
    uv run python -m tools.plugins.update_lock --check    # no network: the archives match the lock (CI)
    uv run python -m tools.plugins.update_lock --plugin software-delivery@1.1.0   # move one plugin

The built-in agents left the core for `VargaFoundation/choregos-agents` (plan 2026-10-27, Decision 6).
The core still runs offline — the tests, `make demo`, `CHOREGOS_FAKES=1`, `docker compose up` — because
the published archives of the plugins it needs are committed here, byte for byte as the source signed
them, and the API image copies them to its offline directory (`/opt/choregos/plugins`).

Refreshing reads the source's signed index (`oci://…/index:latest`), pulls each locked plugin's OCI
artifact at the version the lock names (or the one `--plugin` asks for), verifies its cosign signature
against the source's keyless identity (`--no-verify` skips it, and says so in the lock), checks that the
archive's content digest is the index's, then writes the archive and the lock. Nothing else changes a
file of `plugins/offline/`.

The lock is what `choregos_core.plugins.sources.read_lock` reads (`plugins: {name: {version, digest}}`)
plus where each archive came from: an offline directory that holds a lock refuses any plugin not in it
or with another digest.
"""

from __future__ import annotations

import argparse
import asyncio
import re
import sys
from dataclasses import dataclass
from pathlib import Path
from typing import Any

import yaml
from choregos_core.plugins import PluginError, opened
from choregos_core.plugins.sources import (
    INDEX_MEDIA_TYPE,
    LOCK,
    PLUGIN_MEDIA_TYPE,
    SourceError,
    parse_index,
)
from choregos_core.plugins.versions import Version

ROOT = Path(__file__).resolve().parents[2]
OFFLINE = ROOT / "plugins" / "offline"
INDEX = "ghcr.io/vargafoundation/choregos-agents/index:latest"
IDENTITY = "https://github.com/VargaFoundation/choregos-agents/.github/workflows/publish.yml@refs/heads/main"
ISSUER = "https://token.actions.githubusercontent.com"
MAX_BYTES = 64 * 1024 * 1024
HEADER = (
    "# Generated by tools/plugins/update_lock.py (`make plugins-lock`): do not edit by hand.\n"
    "# The plugins the core ships offline (ADR 0093 §6): each archive of this directory, byte for byte\n"
    "# the source's signed OCI artifact. The API refuses an offline plugin missing from this lock or\n"
    "# whose content digest differs; `tests/tools/test_update_plugins_lock.py` checks the archives.\n"
)


@dataclass(frozen=True)
class Locked:
    name: str
    version: str
    digest: str
    source: str
    artifact: str
    file: str
    signature: str

    def entry(self) -> dict[str, str]:
        return {
            "version": self.version,
            "digest": self.digest,
            "source": self.source,
            "artifact": self.artifact,
            "file": self.file,
            "signature": self.signature,
        }


def read(directory: Path = OFFLINE) -> tuple[str, dict[str, Locked]]:
    """The lock's index reference and its plugins."""
    doc = yaml.safe_load((directory / LOCK).read_text(encoding="utf-8")) or {}
    plugins = {
        str(name): Locked(
            str(name),
            str(entry["version"]),
            str(entry["digest"]),
            str(entry["source"]),
            str(entry.get("artifact", "")),
            str(entry["file"]),
            str(entry.get("signature", "")),
        )
        for name, entry in (doc.get("plugins") or {}).items()
    }
    return str(doc.get("index") or INDEX), plugins


def write(directory: Path, index: str, plugins: dict[str, Locked]) -> None:
    doc: dict[str, Any] = {
        "index": index,
        "plugins": {name: plugins[name].entry() for name in sorted(plugins)},
    }
    text = HEADER + yaml.safe_dump(doc, sort_keys=False, allow_unicode=True)
    (directory / LOCK).write_text(text, encoding="utf-8")


def problems(directory: Path = OFFLINE) -> list[str]:
    """What makes the committed archives disagree with the lock; empty when they agree. No network."""
    found: list[str] = []
    _, locked = read(directory)
    archives = {p.name for p in directory.glob("*.tar.gz")}
    others = sorted(
        p.name
        for p in directory.iterdir()
        if p.name != LOCK and p.name not in archives and p.name != ".gitattributes"
    )
    found += [f"{name}: neither an archive nor the lock" for name in others]
    named = {entry.file for entry in locked.values()}
    found += [f"{name}: an archive the lock does not name" for name in sorted(archives - named)]
    for entry in locked.values():
        path = directory / entry.file
        if not path.is_file():
            found.append(f"{entry.name}: {entry.file} is missing")
            continue
        try:
            with opened(path) as plugin:
                if (plugin.name, plugin.version) != (entry.name, entry.version):
                    found.append(
                        f"{entry.file} holds {plugin.name} {plugin.version}, not {entry.name} {entry.version}"
                    )
                if plugin.digest != entry.digest:
                    found.append(
                        f"{entry.name} {entry.version} is {plugin.digest}; the lock says {entry.digest}"
                    )
        except PluginError as exc:
            found.append(f"{entry.file}: {exc}")
    return found


async def _refresh(
    directory: Path, index_ref: str, wanted: dict[str, str | None], verify: bool, cosign: str
) -> dict[str, Locked]:
    from choregos_adapters.oci import CosignVerifier, OciRegistryClient, parse_ref

    client = OciRegistryClient(timeout_s=60.0)
    verifier = CosignVerifier(
        identity=re.escape(IDENTITY), issuer=re.escape(ISSUER), binary=cosign, timeout_s=120.0
    )

    async def signed(reference: str, manifest: str) -> str:
        if not verify:
            return "not verified (--no-verify)"
        pinned = parse_ref(reference).pinned(manifest)
        verdict = await verifier.verify(pinned)
        if not verdict.verified:
            raise SystemExit(f"{pinned}: {verdict.detail}")
        return f"keyless, {IDENTITY}"

    manifest, content = await client.pull_artifact(index_ref, INDEX_MEDIA_TYPE, 1024 * 1024)
    await signed(index_ref, manifest)
    index = parse_index(content, trusted=True)
    out: dict[str, Locked] = {}
    for name, version in sorted(wanted.items()):
        releases = index.releases.get(name) or {}
        if not releases:
            raise SystemExit(f"{index_ref} offers no plugin `{name}`")
        chosen = version or str(max(Version.parse(v) for v in releases))
        release = releases.get(chosen)
        if release is None or release.oci is None:
            raise SystemExit(
                f"{index_ref} offers `{name}` in {sorted(releases)}, not {chosen} as an OCI artifact"
            )
        artifact, blob = await client.pull_artifact(release.oci, PLUGIN_MEDIA_TYPE, MAX_BYTES)
        signature = await signed(release.oci, artifact)
        file = f"{name}-{chosen}.tar.gz"
        staged = directory / f".{file}.part"
        staged.write_bytes(blob)
        try:
            with opened(staged) as plugin:
                if plugin.digest != release.digest or (plugin.name, plugin.version) != (name, chosen):
                    raise SystemExit(
                        f"{release.oci}: {plugin.name} {plugin.version} {plugin.digest} is not the index's"
                    )
        except BaseException:
            staged.unlink(missing_ok=True)
            raise
        staged.replace(directory / file)
        out[name] = Locked(name, chosen, release.digest, release.oci, artifact, file, signature)
        print(f"{name} {chosen}: {release.digest} ({signature})")
    return out


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0] if __doc__ else None)
    parser.add_argument("--check", action="store_true", help="no network: the archives match the lock")
    parser.add_argument("--plugin", action="append", default=[], help="name[@version] to add or move")
    parser.add_argument("--no-verify", action="store_true", help="skip the cosign signature check")
    parser.add_argument("--directory", type=Path, default=OFFLINE)
    parser.add_argument(
        "--cosign", default="cosign", help="the cosign binary (v3: the bundles the source signs)"
    )
    args = parser.parse_args(argv)
    directory: Path = args.directory
    if args.check:
        found = problems(directory)
        for problem in found:
            print(f"✗ {problem}", file=sys.stderr)
        if not found:
            where = directory.relative_to(ROOT) if directory.is_relative_to(ROOT) else directory
            print(f"{where}: lock and archives agree")
        return 1 if found else 0
    index_ref, locked = read(directory) if (directory / LOCK).is_file() else (INDEX, {})
    wanted: dict[str, str | None] = {name: entry.version for name, entry in locked.items()}
    for spec in args.plugin:
        name, _, version = str(spec).partition("@")
        wanted[name] = version or None
    if not wanted:
        print("nothing to lock: name plugins with --plugin", file=sys.stderr)
        return 1
    try:
        fresh = asyncio.run(_refresh(directory, index_ref, wanted, not args.no_verify, args.cosign))
    except SourceError as exc:
        print(f"✗ {exc.message}", file=sys.stderr)
        return 1
    for name, entry in locked.items():
        if name in fresh and fresh[name].file != entry.file:
            (directory / entry.file).unlink(missing_ok=True)
    write(directory, index_ref, {**locked, **fresh})
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
