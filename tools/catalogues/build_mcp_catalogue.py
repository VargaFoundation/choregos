#!/usr/bin/env python3
"""Generates the MCP server catalogue from a reviewed seed and recorded sources (ADR 0065).

    uv run python -m tools.catalogues.build_mcp_catalogue            # replay the recordings, write the file
    uv run python -m tools.catalogues.build_mcp_catalogue --check    # replay, fail if the file differs (CI)
    uv run python -m tools.catalogues.build_mcp_catalogue --record   # a maintainer, WITH network: refresh
    uv run python -m tools.catalogues.build_mcp_catalogue --discover # candidates outside the seed (network)

Inputs: `mcp/seed.yaml` (the human curation), `mcp/overrides.yaml` (what the registry does not say),
`mcp/exclusions.yaml` (what never enters), and the recordings of the official MCP Registry and of
GitHub's GraphQL API under `tests/fixtures/catalogues/mcp/`. The default mode replays and refuses
the network, so the output is a pure function of those files: byte-deterministic.

Each seed line is resolved, then either kept or dropped with a reason printed on stderr. A line that
cannot be resolved is never kept half-filled.
"""

from __future__ import annotations

import argparse
import difflib
import json
import re
import sys
import urllib.parse
from dataclasses import dataclass
from datetime import date
from pathlib import Path
from typing import Any

import httpx
import yaml
from choregos_core.mcp_catalogue import INSTALL_ORDER, McpEntry

from tools.catalogues import _github, _recording

ROOT = Path(__file__).resolve().parents[2]
SEED_DIR = ROOT / "tools" / "catalogues" / "mcp"
FIXTURES = ROOT / "tests" / "fixtures" / "catalogues" / "mcp"
OUTPUT = ROOT / "packages" / "core" / "src" / "choregos_core" / "mcp_catalogue" / "catalogue.yaml"
#: The console's demo mode answers the catalogue from this file: the real entries, as the API shows them.
WEB_MOCK = ROOT / "apps" / "web" / "src" / "mocks" / "mcp-catalogue.json"
REGISTRY = "https://registry.modelcontextprotocol.io"

#: Open-source licences accepted for a server whose code the operator would host.
OSI_LICENCES = frozenset(
    {
        "MIT", "Apache-2.0", "BSD-2-Clause", "BSD-3-Clause", "ISC", "MPL-2.0", "GPL-2.0", "GPL-3.0",
        "LGPL-2.1", "LGPL-3.0", "AGPL-3.0", "EPL-2.0", "Unlicense", "0BSD", "Zlib", "BSL-1.0",
    }
)  # fmt: skip
AUTH = re.compile(r"^(none|bearer|oauth|header:[A-Za-z0-9-]+)$")
HEADER = (
    "# Generated by tools/catalogues/build_mcp_catalogue.py from tools/catalogues/mcp/ and the\n"
    "# recordings in tests/fixtures/catalogues/mcp/. Do not edit by hand: change the seed and run\n"
    "# `make catalogues`. ADR 0065. Nothing here is enabled by default: an entry is an offer an\n"
    "# administrator installs.\n"
)
#: The order of the keys of an entry in the file.
ENTRY_KEYS = (
    "id", "title", "description", "publisher", "official", "reference", "registry_name",
    "registry_version", "repo", "licence", "terms_url", "transport", "remote", "auth",
    "egress_hosts", "categories", "stars", "stars_as_of", "hosting",
)  # fmt: skip


class GeneratorError(RuntimeError):
    """The inputs contradict each other; fix the seed or the overrides."""


@dataclass(frozen=True)
class Dropped:
    entry_id: str
    reason: str


# ------------------------------------------------------------------------------ inputs


def _load_yaml(name: str) -> Any:
    return yaml.safe_load((SEED_DIR / name).read_text(encoding="utf-8"))


def registry_url(name: str) -> str:
    return f"{REGISTRY}/v0.1/servers/{urllib.parse.quote(name, safe='')}/versions/latest"


def fetch_registry(client: httpx.Client, names: list[str]) -> dict[str, dict[str, Any] | None]:
    """The latest registry record of each name, `None` when the registry answers 404."""
    out: dict[str, dict[str, Any] | None] = {}
    for name in sorted(set(names)):
        response = client.get(registry_url(name))
        if response.status_code == 404:
            out[name] = None
            continue
        response.raise_for_status()
        out[name] = response.json()
    return out


def read_meta(directory: Path) -> dict[str, Any]:
    return json.loads((directory / "meta.json").read_text(encoding="utf-8"))  # type: ignore[no-any-return]


def record_sources(directory: Path, seed: list[dict[str, Any]], token: str) -> None:
    """The one place that touches the network: record the registry and GitHub answers."""
    directory.mkdir(parents=True, exist_ok=True)
    for stale in directory.glob("*.json"):
        stale.unlink()
    with _recording.make_client(directory, record=True) as registry_client:
        fetch_registry(registry_client, [s["registry"] for s in seed if s.get("registry")])
    github_headers = {"Authorization": f"Bearer {token}", "Accept": "application/vnd.github+json"}
    with _recording.make_client(directory, record=True, headers=github_headers) as gh_client:
        _github.fetch_repo_facts(gh_client, [s["repo"] for s in seed if s.get("repo")])
    meta = {
        "recorded_at": date.today().isoformat(),
        "registry": REGISTRY,
        "github": "https://api.github.com/graphql",
    }
    (directory / "meta.json").write_text(json.dumps(meta, indent=1, sort_keys=True) + "\n", encoding="utf-8")


# ------------------------------------------------------------------------------ rules


def host_matches(host: str, pattern: str) -> bool:
    """`*.example.com` matches `example.com` and every subdomain; anything else is exact."""
    if pattern.startswith("*."):
        suffix = pattern[2:]
        return host == suffix or host.endswith("." + suffix)
    return host == pattern


def excluded_host(host: str, rules: list[dict[str, str]]) -> str | None:
    return next((r["reason"] for r in rules if host_matches(host, r["pattern"])), None)


def excluded_name(seed_line: dict[str, Any], rules: list[dict[str, str]]) -> str | None:
    text = " ".join(str(seed_line.get(k, "")) for k in ("id", "title", "registry", "repo")).lower()
    return next((r["reason"] for r in rules if r["pattern"].lower() in text), None)


def reverse_namespace(registry_name: str) -> tuple[str, str | None]:
    """`com.notion/mcp` → (`notion.com`, None); `io.github.getsentry/x` → (`github.com`, `getsentry`)."""
    namespace = registry_name.split("/", maxsplit=1)[0]
    if namespace.startswith("io.github."):
        return "github.com", namespace.removeprefix("io.github.")
    return ".".join(reversed(namespace.split("."))), None


def is_official(
    vendor: dict[str, Any] | None, registry_name: str | None, repo: str | None, remote_host: str | None
) -> bool:
    """The registry namespace, the repository owner or the remote host belongs to the vendor."""
    if not vendor:
        return False
    domains = [d.lower() for d in vendor.get("domains", [])]
    orgs = {o.lower() for o in vendor.get("orgs", [])}
    if registry_name:
        domain, org = reverse_namespace(registry_name)
        if org is not None:
            if org.lower() in orgs:
                return True
        elif any(domain == d or domain.endswith("." + d) for d in domains):
            return True
    if repo and repo.split("/", maxsplit=1)[0].lower() in orgs:
        return True
    return bool(remote_host and any(remote_host == d or remote_host.endswith("." + d) for d in domains))


def pick_remote(
    entry_id: str, record: dict[str, Any] | None, overrides: dict[str, Any], force_stdio: bool
) -> tuple[dict[str, str] | None, list[dict[str, Any]]]:
    """The streamable-http remote of an entry (override first) and the headers the registry declares."""
    if force_stdio:
        return None, []
    override = overrides.get("remotes", {}).get(entry_id)
    remotes = (record or {}).get("server", {}).get("remotes", []) or []
    if override:
        return {"url": override["url"], "protocol": override["protocol"]}, []
    for remote in remotes:
        if remote.get("type") == "streamable-http":
            return {"url": remote["url"], "protocol": "streamable-http"}, remote.get("headers", []) or []
    return None, []


def pick_package(seed_line: dict[str, Any], record: dict[str, Any] | None) -> dict[str, str | None] | None:
    """What an operator would run for a stdio server: the seed's package, else the registry's."""
    if seed_line.get("package"):
        return {"package": seed_line["package"], "version": None}
    packages = (record or {}).get("server", {}).get("packages", []) or []
    for wanted in ("npm", "pypi", "oci"):
        for pkg in packages:
            if pkg.get("registryType") == wanted:
                return {
                    "package": f"{wanted}:{pkg['identifier']}",
                    "version": None if wanted == "oci" else pkg.get("version"),
                }
    return None


# ------------------------------------------------------------------------------ resolution


def _check_registry(
    seed_line: dict[str, Any], registry: dict[str, dict[str, Any] | None]
) -> tuple[dict[str, Any] | None, str | None]:
    """The registry record of the seed line, and the reason to drop it when there is one."""
    name = seed_line.get("registry")
    if not name:
        return None, None
    record = registry.get(name)
    if record is None:
        return None, f"registry name {name} is not in the registry"
    status = record.get("_meta", {}).get("io.modelcontextprotocol.registry/official", {}).get("status")
    if status != "active":
        return None, f"registry status is {status!r}, not active"
    return record, None


def _check_repo(
    seed_line: dict[str, Any], github: dict[str, _github.RepoFacts | None]
) -> tuple[_github.RepoFacts | None, str | None]:
    """The GitHub facts of the seed line's repository, and the reason to drop it when there is one."""
    repo = seed_line.get("repo")
    if not repo:
        return None, None
    parsed = _github.parse_repo(repo)
    facts = github.get(f"{parsed[0]}/{parsed[1]}") if parsed else None
    if facts is None:
        return None, f"repository {repo} not found on GitHub"
    if facts.archived:
        return None, f"repository {repo} is archived"
    return facts, None


def _check_remote(
    entry_id: str,
    auth: str,
    remote: dict[str, str],
    headers: list[dict[str, Any]],
    exclusions: dict[str, Any],
) -> tuple[str, str | None]:
    """The remote's host and the reason to drop it when there is one."""
    parsed = urllib.parse.urlparse(remote["url"])
    if parsed.scheme != "https":
        return "", "the remote is not served over TLS"
    if "{" in remote["url"]:
        return "", "the remote URL needs per-user variables"
    host = (parsed.hostname or "").lower()
    if reason := excluded_host(host, exclusions.get("hosts", [])):
        return host, f"remote host {host}: {reason}"
    requires_bearer = any(
        h.get("isRequired") and str(h.get("name", "")).lower() == "authorization" for h in headers
    )
    if requires_bearer and auth == "none":
        raise GeneratorError(
            f"{entry_id}: the registry requires an Authorization header, the seed says auth none"
        )
    return host, None


def resolve(
    seed_line: dict[str, Any],
    registry: dict[str, dict[str, Any] | None],
    github: dict[str, _github.RepoFacts | None],
    overrides: dict[str, Any],
    exclusions: dict[str, Any],
    recorded_at: str,
) -> dict[str, Any] | Dropped:
    """One seed line → one entry, or the reason it is dropped."""
    entry_id = seed_line["id"]
    if reason := excluded_name(seed_line, exclusions.get("names", [])):
        return Dropped(entry_id, f"excluded: {reason}")
    auth = seed_line["auth"]
    if not AUTH.match(auth):
        raise GeneratorError(f"{entry_id}: auth {auth!r} is not none, bearer, oauth or header:<Name>")

    record, why = _check_registry(seed_line, registry)
    if why:
        return Dropped(entry_id, why)
    facts, why = _check_repo(seed_line, github)
    if why:
        return Dropped(entry_id, why)

    remote, headers = pick_remote(entry_id, record, overrides, seed_line.get("transport") == "stdio")
    host: str | None = None
    if remote is not None:
        host, why = _check_remote(entry_id, auth, remote, headers, exclusions)
        if why:
            return Dropped(entry_id, why)

    hosting: dict[str, str | None] | None = None
    if remote is None:
        hosting = pick_package(seed_line, record)
        if hosting is None:
            return Dropped(entry_id, "no hosted remote and no package to run")

    licence = (facts.licence if facts else None) or overrides.get("licences", {}).get(entry_id)
    if remote is None and licence not in OSI_LICENCES:
        return Dropped(entry_id, f"a hosted server needs an open-source licence, found {licence!r}")

    stars = facts.stars if facts is not None and seed_line.get("stars", True) else None
    registry_name = seed_line.get("registry")
    return {
        "id": entry_id,
        "title": seed_line["title"],
        "description": " ".join(str(seed_line["description"]).split()),
        "publisher": seed_line["publisher"],
        "official": is_official(
            overrides.get("vendors", {}).get(entry_id), registry_name, seed_line.get("repo"), host
        ),
        "reference": bool(seed_line.get("reference", False)),
        "registry_name": registry_name,
        "registry_version": (record or {}).get("server", {}).get("version") if registry_name else None,
        "repo": f"https://github.com/{facts.full_name}" if facts else None,
        "licence": licence,
        "terms_url": None,
        "transport": "remote" if remote else "stdio",
        "remote": remote,
        "auth": auth,
        "egress_hosts": [host] if host else [],
        "categories": sorted(seed_line["categories"]),
        "stars": stars,
        "stars_as_of": recorded_at if stars is not None else None,
        "hosting": hosting,
    }


def build(
    seed: list[dict[str, Any]],
    registry: dict[str, dict[str, Any] | None],
    github: dict[str, _github.RepoFacts | None],
    overrides: dict[str, Any],
    exclusions: dict[str, Any],
    recorded_at: str,
) -> tuple[dict[str, Any], list[Dropped]]:
    """The whole catalogue (as a dict) and the lines that were dropped."""
    ids = [s["id"] for s in seed]
    if len(ids) != len(set(ids)):
        raise GeneratorError(f"duplicate ids in the seed: {sorted({i for i in ids if ids.count(i) > 1})}")
    entries: list[dict[str, Any]] = []
    drops: list[Dropped] = []
    for line in seed:
        result = resolve(line, registry, github, overrides, exclusions, recorded_at)
        if isinstance(result, Dropped):
            drops.append(result)
        else:
            McpEntry.model_validate(result)  # the loader's own model: what we write, the API can read
            entries.append(result)

    def rank(e: dict[str, Any]) -> tuple[int, int, int, str]:
        kind = McpEntry.model_validate(e).install
        return (0 if e["official"] else 1, INSTALL_ORDER[kind], -(e["stars"] or 0), e["id"])

    entries.sort(key=rank)
    document = {
        "schema_version": 1,
        "catalogue_version": overrides["catalogue_version"],
        "generated_at": f"{recorded_at}T00:00:00Z",
        "sources": {
            "registry": f"{REGISTRY} (fetched {recorded_at})",
            "github_stars_as_of": recorded_at,
        },
        "entries": entries,
    }
    return document, drops


def render(document: dict[str, Any]) -> str:
    ordered = dict(document)
    ordered["entries"] = [{k: e[k] for k in ENTRY_KEYS} for e in document["entries"]]
    body = yaml.safe_dump(ordered, sort_keys=False, allow_unicode=True, width=110, default_flow_style=False)
    return HEADER + body


def render_web_mock(document: dict[str, Any]) -> str:
    """The shipped catalogue as `GET /orgs/{org}/mcp-catalogue` answers it for an organisation that
    installed nothing and whose deployment declares no egress: the console's demo data (ADR 0065)."""
    entries = []
    for e in document["entries"]:
        entries.append(
            {k: e[k] for k in ENTRY_KEYS}
            | {
                "origin": "catalogue",
                "install": McpEntry.model_validate(e).install,
                "state": "available",
                "installed_as": [],
                "egress": "unknown",
            }
        )
    meta = {
        "catalogue_version": document["catalogue_version"],
        "generated_at": document["generated_at"],
        "sources": document["sources"],
    }
    return json.dumps({"meta": meta, "entries": entries}, indent=1, ensure_ascii=False) + "\n"


# ------------------------------------------------------------------------------ discover


def discover(seed: list[dict[str, Any]], token: str | None, limit: int) -> None:
    """Prints candidates outside the seed, ranked by stars. Writes nothing; needs the network."""
    known = {s["repo"].lower() for s in seed if s.get("repo")}
    readme = httpx.get(
        "https://raw.githubusercontent.com/punkpeye/awesome-mcp-servers/main/README.md", timeout=60
    ).text
    repos = sorted(
        {
            f"{m.group(1)}/{m.group(2)}"
            for m in re.finditer(r"https://github\.com/([A-Za-z0-9_.-]+)/([A-Za-z0-9_.-]+)", readme)
        }
        - known
    )
    headers = {"Authorization": f"Bearer {token}"} if token else {}
    with httpx.Client(headers=headers, timeout=60) as client:
        facts = _github.fetch_repo_facts(client, [r for r in repos if r.lower() not in known])
    ranked = sorted((f for f in facts.values() if f and not f.archived), key=lambda f: -f.stars)
    for f in ranked[:limit]:
        print(f"{f.stars:>7}  {f.full_name}  {f.licence or '-'}")


# ------------------------------------------------------------------------------ main


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument("--record", action="store_true", help="refresh the recordings from the network first")
    mode.add_argument("--check", action="store_true", help="replay and fail if the committed file differs")
    mode.add_argument("--discover", action="store_true", help="print candidates outside the seed (network)")
    parser.add_argument("--limit", type=int, default=40, help="with --discover: how many to print")
    args = parser.parse_args(argv)

    seed = _load_yaml("seed.yaml")
    overrides = _load_yaml("overrides.yaml")
    exclusions = _load_yaml("exclusions.yaml")

    if args.discover:
        import os

        discover(seed, os.environ.get("GITHUB_TOKEN"), args.limit)
        return 0
    if args.record:
        import os

        token = os.environ.get("GITHUB_TOKEN")
        if not token:
            print("--record needs GITHUB_TOKEN (for example `gh auth token`)", file=sys.stderr)
            return 2
        record_sources(FIXTURES, seed, token)

    meta = read_meta(FIXTURES)
    with _recording.make_client(FIXTURES, record=False) as registry_client:
        registry = fetch_registry(registry_client, [s["registry"] for s in seed if s.get("registry")])
    with _recording.make_client(FIXTURES, record=False) as gh_client:
        github = _github.fetch_repo_facts(gh_client, [s["repo"] for s in seed if s.get("repo")])
    document, drops = build(seed, registry, github, overrides, exclusions, meta["recorded_at"])
    text = render(document)
    for drop in drops:
        print(f"dropped {drop.entry_id}: {drop.reason}", file=sys.stderr)
    print(f"{len(document['entries'])} entries, {len(drops)} dropped", file=sys.stderr)

    outputs = {OUTPUT: text, WEB_MOCK: render_web_mock(document)}
    if args.check:
        stale = False
        for path, wanted in outputs.items():
            current = path.read_text(encoding="utf-8") if path.exists() else ""
            if current != wanted:
                stale = True
                sys.stderr.writelines(
                    difflib.unified_diff(
                        current.splitlines(keepends=True),
                        wanted.splitlines(keepends=True),
                        "committed",
                        "generated",
                    )
                )
                print(f"{path.name} is out of date: run `make catalogues`", file=sys.stderr)
        return 1 if stale else 0
    for path, wanted in outputs.items():
        path.write_text(wanted, encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main())
