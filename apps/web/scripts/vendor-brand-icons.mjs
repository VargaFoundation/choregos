/**
 * Regenerates `src/components/brand-icon-paths.ts` from a pinned simple-icons tarball.
 *
 * Usage (not run in CI, it documents provenance and keeps the vendored paths reviewable):
 *
 *   npm pack simple-icons@16.35.0            # or download the tarball from the npm registry
 *   node scripts/vendor-brand-icons.mjs ./simple-icons-16.35.0.tgz
 *
 * The brands are the ones the connector registry names: see `connector-icon.tsx`.
 * simple-icons is CC0-1.0; the marks themselves are trademarks of their owners (see its DISCLAIMER.md).
 */
import { execFileSync } from "node:child_process";
import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const BRANDS = [
  "git",
  "github",
  "gitlab",
  "jira",
  "confluence",
  "tekton",
  "argo",
  "kubernetes",
  "docker",
  "modelcontextprotocol",
  "pfsense",
  "cilium",
  "nginx",
];
const VERSION = "16.35.0";

const tarball = process.argv[2];
if (!tarball) {
  console.error("usage: node scripts/vendor-brand-icons.mjs <simple-icons-" + VERSION + ".tgz>");
  process.exit(2);
}

const read = (member) => execFileSync("tar", ["-xzOf", tarball, member], { encoding: "utf8" });
const pkg = JSON.parse(read("package/package.json"));
if (pkg.version !== VERSION) {
  console.error(`expected simple-icons ${VERSION}, the tarball is ${pkg.version}`);
  process.exit(1);
}

const lines = BRANDS.map((brand) => {
  const svg = read(`package/icons/${brand}.svg`);
  const path = /<path d="([^"]+)"/.exec(svg)?.[1];
  if (!path) throw new Error(`no path in ${brand}.svg`);
  return `  ${JSON.stringify(brand)}: ${JSON.stringify(path)},`;
});

const out = `// SPDX-License-Identifier: Apache-2.0
// GENERATED by scripts/vendor-brand-icons.mjs from simple-icons@${VERSION} (CC0-1.0, https://simpleicons.org).
// The paths themselves are CC0-1.0 (simple-icons). Do not edit by hand. The marks are trademarks of their owners and are used only to name the product
// they stand for (simple-icons DISCLAIMER). One 24x24 path per brand, drawn with \`fill="currentColor"\`.
export const BRAND_PATHS = {
${lines.join("\n")}
} as const satisfies Record<string, string>;

export type Brand = keyof typeof BRAND_PATHS;
`;
const target = join(dirname(fileURLToPath(import.meta.url)), "..", "src", "components", "brand-icon-paths.ts");
writeFileSync(target, out);
console.log(`wrote ${target} (${BRANDS.length} brands)`);
