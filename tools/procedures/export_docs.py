#!/usr/bin/env python3
"""Writes `docs/procedures/` from the procedures that ship in `choregos_core.procedures` (ADR 0067).

    uv run python tools/procedures/export_docs.py            # writes docs/procedures/
    uv run python tools/procedures/export_docs.py --check    # fails if docs/procedures/ diverges
    uv run python tools/procedures/export_docs.py --mocks apps/web/src/mocks/procedures.json

The app serves the same files with this deployment's URLs filled in; here the placeholders are
shown as `<api_url>`, `<public_url>` and `<org>`, so the documentation cannot drift from the app.
`--mocks` writes the console's mock data (the API's `Procedure` shape, example URLs).
"""

from __future__ import annotations

import argparse
import json
import pathlib
import sys
from typing import Any

from choregos_core import procedures as core

ROOT = pathlib.Path(__file__).resolve().parents[2]
TARGET = ROOT / "docs" / "procedures"
DOCS_CONTEXT = core.Context(api_url="<api_url>", public_url="<public_url>", org="<org>")
MOCK_CONTEXT = core.Context(
    api_url="https://choregos.example.com", public_url="https://choregos.example.com", org="acme"
)

AUDIENCE = {
    "org_admin": "an organisation administrator",
    "project_owner": "a project owner",
    "operator": "the person who operates the platform",
    "everyone": "anyone",
}
AREAS = (
    ("connector", "Connectors"),
    ("source", "Knowledge sources"),
    ("door_client", "Clients of the MCP door"),
    ("agent", "External agents"),
)

HEADER = (
    "<!-- Generated by tools/procedures/export_docs.py from "
    "packages/core/src/choregos_core/procedures/. Do not edit by hand: `make procedures` regenerates it, "
    "`make procedures-check` refuses a difference. -->\n\n"
)


def render_page(proc: core.Procedure) -> str:
    front = proc.front
    lines = [HEADER + f"# {front.title}", ""]
    lines.append(
        f"For {AUDIENCE[front.audience]}. Procedure `{front.id}`, version {front.version}, "
        f"reviewed {front.reviewed.isoformat()} against the vendor's own pages."
    )
    if front.link:
        lines += ["", f"In the console this procedure is the page `{front.link}`."]
    lines.append("")
    for section in core.render(proc, DOCS_CONTEXT):
        lines += [f"## {section.title}", "", section.markdown, ""]
    if front.fields:
        lines += ["## Fields", "", "| Field | What to put in it |", "| :-- | :-- |"]
        lines += [f"| `{name}` | {text} |" for name, text in sorted(front.fields.items())]
        lines.append("")
    if front.egress:
        lines += ["## Network egress", "", "Hosts the platform must be allowed to reach:", ""]
        lines += [f"- `{host}`" for host in front.egress]
        lines.append("")
    if front.vendor_docs:
        lines += ["## Vendor documentation", ""]
        lines += [f"- [{d.title}]({d.url})" for d in front.vendor_docs]
        lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def render_index(procedures: dict[str, core.Procedure]) -> str:
    lines = [
        HEADER + "# Setup procedures",
        "",
        "One procedure per connector type, knowledge source kind, MCP-door client and external agent kind "
        "([ADR 0067](../adr/0067-a-procedure-per-connector-and-agent-type.md)). The console shows the same "
        "text beside the form where you add the thing, with this deployment's own URLs filled in. A "
        "deployment adds its own notes (`<id>.site.md`) or procedures through `CHOREGOS_PROCEDURES_EXTRA`; "
        "see [deployment](../deployment.md#site-notes-on-the-setup-procedures).",
        "",
        f"{len(procedures)} procedures.",
        "",
    ]
    for key, label in AREAS:
        rows = [p for p in procedures.values() if p.target[0] == key]
        if not rows:
            continue
        lines += [
            f"## {label}",
            "",
            "| Procedure | For | Applies to | Reviewed |",
            "| :-- | :-- | :-- | :-- |",
        ]
        for proc in sorted(rows, key=lambda p: p.id):
            preset = "".join(f" ({k.replace('_', ' ')} `{v}`)" for k, v in proc.qualifiers.items())
            audience = AUDIENCE[proc.front.audience]
            lines.append(
                f"| [{proc.front.title}]({proc.id}.md) | {audience} | `{proc.target[1]}`{preset} "
                f"| {proc.front.reviewed.isoformat()} |"
            )
        lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def render_all() -> dict[str, str]:
    """Filename to content, for every page and the index. Only what ships, never a deployment's additions."""
    shipped = core.load().procedures
    pages = {f"{pid}.md": render_page(proc) for pid, proc in sorted(shipped.items())}
    pages["README.md"] = render_index(shipped)
    return pages


def mock_data() -> list[dict[str, Any]]:
    """The API's `Procedure` shape for every shipped procedure, with example URLs."""
    out: list[dict[str, Any]] = []
    for pid, proc in sorted(core.load().procedures.items()):
        front = proc.front
        out.append(
            {
                "id": pid,
                "title": front.title,
                "version": front.version,
                "audience": front.audience,
                "applies_to": dict(front.applies_to),
                "link": front.link,
                "reviewed": front.reviewed.isoformat(),
                "sections": [
                    {"key": s.key, "title": s.title, "markdown": s.markdown}
                    for s in core.render(proc, MOCK_CONTEXT)
                ],
                "values": core.values_of(proc, MOCK_CONTEXT),
                "egress": list(front.egress),
                "fields": dict(front.fields),
                "vendor_docs": [{"title": d.title, "url": d.url} for d in front.vendor_docs],
                "origin": proc.origin,
            }
        )
    return out


def differences(target: pathlib.Path = TARGET) -> list[str]:
    """What differs between the files on disk and what the procedures render to."""
    wanted = render_all()
    present = {p.name: p for p in target.glob("*.md")} if target.is_dir() else {}
    problems = [f"{name}: missing" for name in sorted(set(wanted) - set(present))]
    problems += [f"{name}: no procedure of that name" for name in sorted(set(present) - set(wanted))]
    for name in sorted(set(wanted) & set(present)):
        if present[name].read_text(encoding="utf-8") != wanted[name]:
            problems.append(f"{name}: differs from what the procedure renders")
    return problems


def write(target: pathlib.Path = TARGET) -> int:
    wanted = render_all()
    target.mkdir(parents=True, exist_ok=True)
    for stale in target.glob("*.md"):
        if stale.name not in wanted:
            stale.unlink()
    for name, content in wanted.items():
        (target / name).write_text(content, encoding="utf-8")
    return len(wanted)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    parser.add_argument("--check", action="store_true", help="fail if docs/procedures/ diverges")
    parser.add_argument("--mocks", metavar="PATH", help="write the console's mock data to PATH")
    args = parser.parse_args(argv)
    if args.mocks:
        path = pathlib.Path(args.mocks)
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(json.dumps(mock_data(), indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
        print(f"[procedures] wrote {path}")
        return 0
    if args.check:
        problems = differences()
        for problem in problems:
            print(f"[procedures] {problem}", file=sys.stderr)
        if problems:
            print("[procedures] run `make procedures` and commit the result", file=sys.stderr)
        return 1 if problems else 0
    print(f"[procedures] wrote {write()} files in {TARGET.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
