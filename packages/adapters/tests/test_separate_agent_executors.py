SECRETS = ("token", "gk", "remote")


def _spec(**changes: Any) -> StageJobSpec:
    base: dict[str, Any] = {
        "run_id": "r-1",
        "project_slug": "demo",
        "namespace": "proj-demo-runners",
        "runner_image": "registry.example/choregos-runner:1.0",
        "api_url": "http://choregos-api:8000",
        "run_token": "token",
        "gateway_key": "gk",
        "env": {"HTTP_PROXY": "http://egress:3128", "CHOREGOS_ENV": "dev"},
        "labels": {"choregos/work-item": "DEMO-1"},
        "runtime_class": "gvisor",
    }
    return StageJobSpec(**{**base, **changes})


def _executor(*, gated: bool = True, client: Any = None) -> KubernetesJobExecutor:
    return KubernetesJobExecutor(
        client=client or object(),  # type: ignore[arg-type]
        env_from_secrets=["git-credentials"],
        image_pull_secrets=["pull"],
        egress_gate=EgressGate() if gated else None,
    )


class _Docker(LocalDockerExecutor):
    def __init__(self) -> None:
        super().__init__()
        self.calls: list[list[str]] = []
        self.envs: list[dict[str, str] | None] = []

    async def _run_raw(
        self, *args: str, timeout: float = 120.0, env: dict[str, str] | None = None
    ) -> tuple[int, bytes, str]:
        self.calls.append(list(args))
        self.envs.append(env)
        return (1 if args[0] == "inspect" else 0), b"", ""


async def _render() -> dict[str, Any]:
    """The renderings the fixture holds, from the code as it is now, under `process`."""
    out: dict[str, Any] = {}
    for gated in (False, True):
        executor = _executor(gated=gated)
        out[f"job-gate={gated}"] = executor._job(_spec(), "run-r-1")
        out[f"job-hosted-gate={gated}"] = executor._job(_spec(agent_container=HOSTED), "run-r-1")
    docker = _Docker()
    for spec in (_spec(), _spec(run_id="r-2", agent_container=HOSTED)):
        await docker.start(spec)
    out["docker"] = docker.calls
    return out


async def test_process_renders_exactly_what_it_did_before() -> None:
    """The rollback: a deployment that sets `process` gets the Job and the containers of 0.27.15."""
    assert json.loads(json.dumps(await _render())) == json.loads(BEFORE.read_text(encoding="utf-8"))


def test_both_executors_declare_the_capability() -> None:
    assert SEPARATE_AGENT in KubernetesJobExecutor.capabilities
    assert SEPARATE_AGENT in LocalDockerExecutor.capabilities


