"""The catalogue of default skills shipped with the platform (ADR 0065).

`catalogue.yaml` is generated by `tools/catalogues/build_skill_catalogue.py` from a reviewed seed and
recorded commits of public repositories; nothing here reads the network. An entry is an offer:
installing it publishes an ordinary skill version through the supply-chain gate (ADR 0050), which
runs again at install, so the `risk` the file carries is information and never a pass.

Two deliveries. `bundled`: the skill's files are vendored in this package under `bundled/<id>/` with
their licence and a `PROVENANCE.json` of sha256s, so an install needs no network; only permissive
licences and low or medium risk. `git`: everything else; the entry holds a pinned commit and path and
the install fetches that commit.
"""

from __future__ import annotations

import functools
import hashlib
import json
from datetime import date
from pathlib import Path
from typing import Any, Literal

from choregos_contracts.skill_files import encode_binary, is_inert_binary_path
from pydantic import BaseModel, ConfigDict

from choregos_core.catalogues import CatalogueMeta, meta_of, read_catalogue

HERE = Path(__file__).parent
CATALOGUE_PATH = HERE / "catalogue.yaml"
SCHEMA_PATH = HERE / "schema.json"
BUNDLED_DIR = HERE / "bundled"


class BundleTamperedError(RuntimeError):
    """A bundled skill is not what its provenance says: the image was altered after it was built."""


class SkillSignals(BaseModel):
    model_config = ConfigDict(extra="forbid")

    stars: int | None = None
    stars_as_of: date | None = None


class SkillEntry(BaseModel):
    """One catalogue line. `risk` is what the gate said when the catalogue was generated."""

    model_config = ConfigDict(extra="forbid")

    id: str
    title: str
    description: str
    publisher: str
    repo: str
    sha: str
    path: str
    licence: str
    licence_class: Literal["permissive", "copyleft"]
    files: int
    bytes: int
    digest: str
    risk: Literal["low", "medium", "high"]
    findings_count: int
    categories: list[str]
    signals: SkillSignals
    delivery: Literal["bundled", "git"]


class SkillCatalogue(BaseModel):
    meta: CatalogueMeta
    entries: list[SkillEntry]

    def by_id(self, entry_id: str) -> SkillEntry | None:
        return next((e for e in self.entries if e.id == entry_id), None)


@functools.lru_cache(maxsize=1)
def load() -> SkillCatalogue:
    """The shipped catalogue, validated once."""
    raw = read_catalogue(CATALOGUE_PATH, SCHEMA_PATH)
    return SkillCatalogue(meta=meta_of(raw), entries=[SkillEntry.model_validate(e) for e in raw["entries"]])


def entry(entry_id: str) -> SkillEntry | None:
    return load().by_id(entry_id)


class BundledSkill(BaseModel):
    """A bundled skill as the image holds it, checked against its provenance."""

    files: dict[str, str]
    #: The licence files the gate reads to name the licence (`{"LICENSE": text}` for a repository's own).
    repo_licences: dict[str, str]
    provenance: dict[str, Any]


def _sha256(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def read_bundled(entry_id: str, root: Path | None = None) -> BundledSkill:
    """The files of a bundled skill, each verified against `PROVENANCE.json`.

    Raises `BundleTamperedError` when a file was changed, added or removed since the catalogue was
    generated: what is installed must be what was reviewed."""
    base = (root or BUNDLED_DIR) / entry_id
    try:
        provenance = json.loads((base / "PROVENANCE.json").read_text(encoding="utf-8"))
    except (OSError, ValueError) as problem:
        raise BundleTamperedError(f"{entry_id}: PROVENANCE.json cannot be read: {problem}") from problem
    expected: dict[str, str] = provenance["files"]
    on_disk = {
        p.relative_to(base / "files").as_posix(): p
        for p in sorted((base / "files").rglob("*"))
        if p.is_file()
    }
    if set(on_disk) != set(expected):
        changed = sorted(set(on_disk) ^ set(expected))
        raise BundleTamperedError(f"{entry_id}: the files differ from the provenance: {changed}")
    files: dict[str, str] = {}
    for relative, path in on_disk.items():
        data = path.read_bytes()
        if _sha256(data) != expected[relative]:
            raise BundleTamperedError(f"{entry_id}: {relative} does not match its recorded sha256")
        # a font or an image goes back to the base64 it is stored as, so the digest still matches
        files[relative] = encode_binary(data) if is_inert_binary_path(relative) else data.decode("utf-8")
    licence = provenance["licence_file"]
    repo_licences: dict[str, str] = {}
    if licence["scope"] == "repository":
        stored = base / licence["stored_as"]
        try:
            data = stored.read_bytes()
        except OSError as problem:
            raise BundleTamperedError(f"{entry_id}: the licence file is missing") from problem
        if _sha256(data) != licence["sha256"]:
            raise BundleTamperedError(f"{entry_id}: the licence file does not match its recorded sha256")
        repo_licences[licence["name"]] = data.decode("utf-8")
    return BundledSkill(files=files, repo_licences=repo_licences, provenance=provenance)
