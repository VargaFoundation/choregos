"""Loading and validating a shipped catalogue (ADR 0065).

An MCP server catalogue and a skills catalogue are the same kind of object: a reviewed file in the
image, generated by `tools/catalogues/` from recorded sources, validated by a JSON Schema, and
carrying the provenance of how it was built. This module is what they share: reading the file,
validating it, checking that ids are unique, and the `CatalogueMeta` the API returns beside the
entries. What an entry *means* (what installing it does) stays with each catalogue.
"""

from __future__ import annotations

import json
import re
from datetime import datetime
from pathlib import Path
from typing import Any

import yaml
from jsonschema import Draft202012Validator
from pydantic import BaseModel, ConfigDict

#: The shape of `catalogue_version`: a CalVer, `2026.10.0`.
CALVER = re.compile(r"^\d{4}\.\d{1,2}\.\d+$")


class CatalogueError(ValueError):
    """A catalogue file that does not honour its schema or its own invariants."""


class CatalogueMeta(BaseModel):
    """Which file this is, when it was built, from what: the same object in every catalogue."""

    model_config = ConfigDict(extra="forbid")

    catalogue_version: str
    generated_at: datetime
    sources: dict[str, str] = {}


def read_catalogue(path: Path, schema_path: Path) -> dict[str, Any]:
    """The catalogue file as a dict, validated against its schema.

    Raises `CatalogueError` listing every schema violation (at most twenty), a duplicate id, or a
    `catalogue_version` that is not a CalVer.
    """
    raw = yaml.safe_load(path.read_text(encoding="utf-8"))
    if not isinstance(raw, dict):
        raise CatalogueError(f"{path.name}: the top level must be a mapping")
    schema = json.loads(schema_path.read_text(encoding="utf-8"))
    validator = Draft202012Validator(schema)
    errors = sorted(validator.iter_errors(raw), key=lambda e: list(e.absolute_path))
    if errors:
        lines = [f"{'/'.join(str(p) for p in e.absolute_path) or '<root>'}: {e.message}" for e in errors[:20]]
        raise CatalogueError(f"{path.name} does not honour its schema:\n" + "\n".join(lines))
    version = str(raw["catalogue_version"])
    if not CALVER.match(version):
        raise CatalogueError(f"{path.name}: catalogue_version {version!r} is not a CalVer such as 2026.10.0")
    seen: set[str] = set()
    for entry in raw["entries"]:
        if entry["id"] in seen:
            raise CatalogueError(f"{path.name}: duplicate id {entry['id']!r}")
        seen.add(entry["id"])
    return raw


def meta_of(raw: dict[str, Any]) -> CatalogueMeta:
    """The `CatalogueMeta` of a validated catalogue."""
    return CatalogueMeta(
        catalogue_version=str(raw["catalogue_version"]),
        generated_at=raw["generated_at"]
        if isinstance(raw["generated_at"], datetime)
        else datetime.fromisoformat(str(raw["generated_at"]).replace("Z", "+00:00")),
        sources={str(k): str(v) for k, v in (raw.get("sources") or {}).items()},
    )
