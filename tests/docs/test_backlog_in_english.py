def _load_checker() -> ModuleType:
    spec = importlib.util.spec_from_file_location(
        "check_english_for_backlog", ROOT / "tools" / "check_english.py"
    )
    assert spec is not None and spec.loader is not None
    module = importlib.util.module_from_spec(spec)
    sys.modules[spec.name] = module
    spec.loader.exec_module(module)
    return module


def test_backlog_has_no_french() -> None:
    checker = _load_checker()
    content = (ROOT / BACKLOG).read_text(encoding="utf-8")
    findings = checker.file_findings(BACKLOG, content)
    assert findings == [], "\n".join(
        f"{f.path}:{f.line}: {f.reason}: {f.text.strip()[:100]}" for f in findings[:40]
    )


def test_backlog_ids_unchanged() -> None:
    backlog = yaml.safe_load((ROOT / BACKLOG).read_text(encoding="utf-8"))
    ids = tuple(story["id"] for story in backlog["stories"])
    assert ids[: len(RECORDED_IDS)] == RECORDED_IDS
