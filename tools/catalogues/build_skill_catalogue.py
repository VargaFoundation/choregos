#!/usr/bin/env python3
"""Generates the skills catalogue from a reviewed seed and recorded commits of public repositories (ADR 0065).

    uv run python -m tools.catalogues.build_skill_catalogue           # replay the recordings, write the files
    uv run python -m tools.catalogues.build_skill_catalogue --check   # replay, fail if a file differs
    uv run python -m tools.catalogues.build_skill_catalogue --record  # a maintainer, WITH network: re-pin

What it writes: `catalogue.yaml`, the bundled starter set under `bundled/<id>/` (the skills' files,
their licence and a `PROVENANCE.json` of sha256s) and `THIRD_PARTY_NOTICES.md`. All three are a pure
function of the seed, the publisher and exclusion files and the recordings under
`tests/fixtures/catalogues/skills/`, so replaying them is byte-deterministic.

Each skill goes through the code the platform runs at install: `read_tarball` reads it, `detect_licence`
names its licence, `skill_gate.assess` gives its risk and `skills.empreinte` its digest. The generator
imports them from `choregos_api` rather than copying them, so what the catalogue says of a skill is what
the gate will say again when it is installed.
"""

