def _pod(**changes: Any) -> dict[str, Any]:
    job = _executor()._job(_spec(agent_isolation="container", **changes), "run-r-1")
    pod: dict[str, Any] = job["spec"]["template"]["spec"]
    return pod


def _init(pod: dict[str, Any], name: str) -> dict[str, Any]:
    return next(c for c in pod["initContainers"] if c["name"] == name)


def test_the_jobs_agent_is_a_native_sidecar_after_the_gate_holding_nothing_of_the_run() -> None:
    pod = _pod()
    assert [c["name"] for c in pod["initContainers"]] == [GATE_CONTAINER, "agent"], "the gate stays first"
    agent = _init(pod, "agent")
    assert agent["restartPolicy"] == "Always"
    assert agent["args"] == ["launcher", "--port", str(separate_agent.LAUNCHER_PORT)]
    assert agent["image"] == "registry.example/choregos-runner:1.0", "the platform's image, no second pull"
    text = yaml.safe_dump(agent)
    for forbidden in ("secretKeyRef", "secretRef", "envFrom", "git-credentials", "CHOREGOS_RUN"):
        assert forbidden not in text
    assert {e["name"] for e in agent["env"]} == {"TMPDIR", "HOME"}
    assert {m["name"]: m["mountPath"] for m in agent["volumeMounts"]} == {
        "workspace": "/workspace",
        "exchange": "/exchange",
        "agent-tmp": "/tmp",
    }
    security = agent["securityContext"]
    assert security["runAsUser"] == 1001 and security["runAsGroup"] == 1000
    assert security["readOnlyRootFilesystem"] is True and security["runAsNonRoot"] is True
    assert security["allowPrivilegeEscalation"] is False and security["capabilities"] == {"drop": ["ALL"]}
    assert pod["securityContext"]["fsGroup"] == 1000, "the group both share"
    assert pod["automountServiceAccountToken"] is False
    assert pod["enableServiceLinks"] is False


def test_the_runner_shares_the_tree_and_the_exchange_only_and_is_told_where_the_agent_is() -> None:
    pod = _pod()
    agent, (runner,) = _init(pod, "agent"), pod["containers"]
    runner_mounts = {m["name"] for m in runner["volumeMounts"]}
    agent_mounts = {m["name"] for m in agent["volumeMounts"]}
    assert runner_mounts & agent_mounts == {"workspace", "exchange"}
    env = {e["name"]: e.get("value") for e in runner["env"]}
    assert env["CHOREGOS_RUNNER_AGENT_ISOLATION"] == "container"
    assert env["CHOREGOS_RUNNER_LAUNCHER_PORT"] == "8766"
    assert env["TMPDIR"] == "/exchange"
    names = [e["name"] for e in runner["env"]]
    assert len(names) == len(set(names)), "one value per variable"
    assert runner["envFrom"] == [{"secretRef": {"name": "git-credentials"}}], "credentials stay here"
    assert {"name": "exchange", "emptyDir": {}} in pod["volumes"]


