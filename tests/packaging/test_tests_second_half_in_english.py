"""S45-31: the second half of the tests tree is English, and the former French names are gone.

`tools/check_english.py` counts French prose lines, French declared names and French path
components in every tracked file. This test runs its tree scan over the directories this story
renamed and translated (conformance, e2e, cluster, live, packaging, build, web, tools, procedures
and the fixtures) and refuses any finding, so a French comment or a French local name cannot come
back without the suite turning red.

Three directories used to have a French name (see `OLD_PATHS`). Nothing but the plan, the reference
pages (renamed by their own story) and recorded trial data may still name them: a code or CI
reference to an old path would be a dead link.
"""

from __future__ import annotations

import importlib.util
import pathlib
import subprocess
import sys
from types import ModuleType

ROOT = pathlib.Path(__file__).resolve().parents[2]
PREFIXES = (
    "tests/conformance/",
    "tests/e2e/",
    "tests/cluster/",
    "tests/live/",
    "tests/packaging/",
    "tests/build/",
    "tests/web/",
    "tests/tools/",
    "tests/procedures/",
    "tests/fixtures/",
    "tests/README.md",
)
#: Owned by another story: the recorded fixture repositories and tickets (S45-24).
EXCLUDED = ("tests/fixtures/repos/", "tests/fixtures/tickets/")
#: The old paths, split so that this file does not name them.
OLD_PATHS = (
    "tests/" + "paquets",  # lang: fr-ok
    "conformance/" + "connecteurs",  # lang: fr-ok
    "conformance/" + "executeurs",  # lang: fr-ok
)
#: Where an old path may still appear: the plan and the reference pages (S45-44), the baselines
#: (regenerated by the integrator), ADR 0053 and 0098 (they record the paths they measured) and
#: the recorded trial data, which is a measurement, not code.
ALLOWED = (
    ":(exclude,glob)docs/*.md",
    ":(exclude)docs/plan",
    ":(exclude)docs/upgrade-notes",
    ":(exclude)tools/english_baseline",
    ":(exclude)docs/adr",
    ":(exclude)trials/graphify",
    ":(exclude)tests/language",
)


def _load_checker() -> ModuleType:
    spec = importlib.util.spec_from_file_location(
        "check_english_for_tests_second_half", ROOT / "tools" / "check_english.py"
    )
    assert spec is not None and spec.loader is not None
    module = importlib.util.module_from_spec(spec)
    sys.modules[spec.name] = module
    spec.loader.exec_module(module)
    return module


def test_owned_test_dirs_have_no_french() -> None:
    checker = _load_checker()
    findings = [f for f in checker.scan_tree(PREFIXES) if not f.path.startswith(EXCLUDED)]
    assert findings == [], "\n".join(
        f"{f.path}:{f.line}: {f.reason}: {f.text.strip()[:100]}" for f in findings
    )


def test_no_code_or_ci_names_the_old_test_paths() -> None:
    for old in OLD_PATHS:
        result = subprocess.run(
            ["git", "grep", "-n", "-F", old, "--", ".", *ALLOWED],
            cwd=ROOT,
            capture_output=True,
            text=True,
            check=False,
        )
        assert result.returncode == 1, f"{old} is still named:\n{result.stdout}"
    assert (ROOT / "tests" / "packaging").is_dir()
    assert (ROOT / "tests" / "conformance" / "connectors").is_dir()
    assert (ROOT / "tests" / "conformance" / "executors").is_dir()
    for old in OLD_PATHS:
        assert not (ROOT / old).exists(), old
